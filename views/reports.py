"""Management reports generated from live data (Excel workbook + printable HTML)."""
from __future__ import annotations

import html
import io
from datetime import date

import pandas as pd
import streamlit as st

from hub import audit, db, engine_alloc, engine_risk, metrics, ui
from hub.i18n import lang, t, tf


def build(cid: int) -> dict[str, pd.DataFrame]:
    ph = metrics.projects_health(cid)
    wl = engine_alloc.workload(cid)
    rg = engine_risk.register(cid, lang())
    ta = db.df("""SELECT e.name, e.department, tr.name AS course, ta.status, ta.due_date FROM training_assignments ta
                  JOIN employees e ON e.id = ta.employee_id JOIN trainings tr ON tr.id = ta.training_id WHERE ta.company_id = ?""", (cid,))
    ev = db.df("""SELECT c.name AS client, ce.evidence_type, ce.status, ce.due_date FROM compliance_evidence ce JOIN clients c ON c.id = ce.client_id
                  WHERE ce.company_id = ?""", (cid,))
    sub = metrics.subcontractor_tasks_at_risk(cid)
    sheets = {
        "Projects": ph[["code", "name", "client", "manager", "status", "priority", "progress", "budget", "actual_spend", "forecast_spend",
                        "budget_util", "health", "health_reasons", "end_date"]] if not ph.empty else ph,
        "Workload": wl[["name", "location", "department", "capacity", "effective_capacity", "allocated", "utilisation", "band",
                        "project_list", "overdue_tasks", "upcoming_deadlines"]].sort_values("utilisation", ascending=False) if not wl.empty else wl,
        "Risks": rg[rg["status"].isin(engine_risk.OPEN_STATUSES)][["code", "display_title", "case_category", "probability", "impact", "score",
                                                                  "priority", "status", "evidence_status", "owner", "display_explanation",
                                                                  "recommended_action"]] if not rg.empty else rg,
        "Training": ta,
        "GDPR evidence": ev,
        "Subcontractor tasks at risk": sub[["subcontractor", "project_code", "code", "title", "due_date", "status", "completion"]] if not sub.empty else sub,
    }
    return sheets


def render(ctx: dict) -> None:
    cid, company, user = ctx["cid"], ctx["company"], ctx["user"]
    ui.page_header("reports", t("Management reports"), t("Generated from live data at the time of download"))
    sheets = build(cid)
    ph, wl, rg = sheets["Projects"], sheets["Workload"], sheets["Risks"]
    today = date.today()
    summary = [
        (t("Active projects"), int((ph["status"] == "Active").sum()) if not ph.empty else 0),
        (t("Projects at risk or critical"), int(ph["health"].isin(["At risk", "Critical"]).sum()) if not ph.empty else 0),
        (t("Employees at overcapacity"), int((wl["band"] == "Overcapacity").sum()) if not wl.empty else 0),
        (t("Open critical risks"), int((rg["priority"] == "Critical").sum()) if not rg.empty else 0),
        (t("Open high risks"), int((rg["priority"] == "High").sum()) if not rg.empty else 0),
        (t("Training completion rate"), f"{metrics.training_rate(cid):.0f}%"),
        (t("Subcontractor tasks at risk"), len(sheets["Subcontractor tasks at risk"])),
    ]
    st.markdown("**" + t("Executive summary") + f" — {company['name']} — {today}**")
    ui.table(pd.DataFrame(summary, columns=["Indicator", "Value"]).astype(str), {"Indicator": "Indicator", "Value": "Value"})
    st.markdown("**" + t("Top risks") + "**")
    ui.table(rg.head(10), {"code": "Code", "display_title": "Risk", "score": "Score", "priority": "Priority", "owner": "Owner"}, translate_values=("priority",))

    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        pd.DataFrame(summary, columns=["Indicator", "Value"]).astype(str).to_excel(xw, sheet_name="Summary", index=False)
        for name, df in sheets.items():
            (df if df is not None and not df.empty else pd.DataFrame({"info": ["no data"]})).to_excel(xw, sheet_name=name[:31], index=False)
        pd.DataFrame({"note": ["Generated by AI Project & Risk Intelligence Hub (prototype).",
                               "Demo data: company facts from the NOVATECH case study; people, clients, figures are fictional sample records.",
                               "Risk scores: Probability x Impact, rule-based and explainable; no trained AI model."]}).to_excel(xw, sheet_name="About", index=False)
    rows = "".join(f"<tr><td>{html.escape(str(a))}</td><td><b>{html.escape(str(b))}</b></td></tr>" for a, b in summary)

    def tbl(df: pd.DataFrame, cols: dict) -> str:
        if df is None or df.empty:
            return "<p>-</p>"
        d = df[[c for c in cols if c in df.columns]].rename(columns={k: t(v) for k, v in cols.items()})
        return d.to_html(index=False, escape=True, border=0, classes="t")
    rep = f"""<!doctype html><html><head><meta charset="utf-8"><title>{html.escape(t('Management report'))} - {html.escape(company['name'])}</title>
    <style>body{{font-family:Inter,Arial,sans-serif;color:#1b2a3d;margin:32px;max-width:1100px}} h1{{font-size:22px}} h2{{font-size:16px;margin-top:28px;border-bottom:2px solid #1f3a5f;padding-bottom:4px}}
    table.t,table.s{{border-collapse:collapse;width:100%;font-size:12px}} .t th,.t td,.s td{{border-bottom:1px solid #e3e8ef;padding:5px 6px;text-align:left}} .t th{{background:#f4f6f9}}
    .note{{font-size:11px;color:#6b7686}}</style></head><body>
    <h1>{html.escape(t('Management report'))} — {html.escape(company['name'])}</h1><div class="note">{today} · {html.escape(user['name'])}</div>
    {'<p class="note">' + html.escape(t('Demonstration workspace: company facts come from the NOVATECH case study; people, clients, contracts, figures and signals are fictional sample records. Nothing here is a confirmed incident.')) + '</p>' if company.get('is_demo') else ''}
    <h2>{html.escape(t('Executive summary'))}</h2><table class="s">{rows}</table>
    <h2>{html.escape(t('Projects'))}</h2>{tbl(ph, {"code": "ID", "name": "Project", "progress": "Progress %", "budget_util": "Budget used %", "health": "Health", "health_reasons": "Why"})}
    <h2>{html.escape(t('Top risks'))}</h2>{tbl(rg.head(15), {"code": "Code", "display_title": "Risk", "score": "Score", "priority": "Priority", "owner": "Owner", "recommended_action": "Recommended action / controls"})}
    <h2>{html.escape(t('Employees at overcapacity'))}</h2>{tbl(wl[wl['band'] == 'Overcapacity'] if not wl.empty else wl, {"name": "Employee", "allocated": "Allocated h", "effective_capacity": "Effective", "utilisation": "Workload %", "project_list": "Projects"})}
    <p class="note">{html.escape(t('Risk scores = Probability × Impact (1–5). Rule-based, explainable engine; no trained AI model.'))}</p></body></html>"""
    c1, c2 = st.columns(2)
    if c1.download_button("📊 " + t("Download Excel report"), buf.getvalue(), f"management_report_{today}.xlsx",
                          "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", width="stretch"):
        audit.log(cid, user["email"], "report_downloaded", "report", "xlsx")
    if c2.download_button("🖨️ " + t("Download printable HTML report"), rep.encode("utf-8"), f"management_report_{today}.html", "text/html", width="stretch"):
        audit.log(cid, user["email"], "report_downloaded", "report", "html")
    st.caption(t("Open the HTML report and use the browser's Print → Save as PDF to obtain a PDF."))
    _ = tf
